class PassivePolicy:
    """Take no actions and advance exactly one simulated minute per decision."""
    def __init__(self, guard=lambda: None, on_error=lambda _: None):
        self._guard = guard
        self._on_error = on_error

    def act(self, host, observation):
        try:
            self._guard()
            host.advance(1)
            self._guard()
        except Exception as exc:
            self._on_error(exc)
            raise


def load_key(path, *, resume):
    from eval.qualify_source_restricted_day_v1 import _check_path
    _check_path(path, existing=resume)
    if resume:
        fd = os.open(path, os.O_RDONLY | os.O_NOFOLLOW)
        with os.fdopen(fd, 'rb') as stream:
            key = stream.read(33)
        if len(key) != 32:
            raise ValueError('invalid continuation key')
        return key
    key = secrets.token_bytes(32)
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    with os.fdopen(fd, 'wb') as stream:
        stream.write(key)
        stream.flush()
        os.fsync(stream.fileno())
    return key


class UnscoredHost:
    """Adapt the raw private host to the runner's terminal status vocabulary."""
    def __init__(self, host):
        self._host = host

    def situation(self):
        result = self._host.situation()
        if result['status'] == 'unsupported':
            result = dict(result, status='end_unscored')
        return result

    def advance(self, minutes):
        self._host.advance(minutes)


def run(args):
    from eval.qualify_source_restricted_day_v1 import qualify, BlockedCase, SCOPE, REWARD_VERSION
    from wildfire_source_restricted_v1 import RestrictedSourceIncidentV1
    from wildfire_source_restricted_scored_v1 import RestrictedSourceScoredV1, verify_outcome

    error_path = args.checkpoint.with_name(args.checkpoint.name + '.errors.jsonl')
    if not args.resume and error_path.exists():
        raise ValueError('error journal already exists')
    def record_error(stage, public_id, exc):
        flags = os.O_WRONLY | os.O_APPEND | os.O_CREAT | os.O_NOFOLLOW
        fd = os.open(error_path, flags, 0o600)
        try:
            info = os.fstat(fd)
            if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
                    or info.st_mode & 0o077 or info.st_nlink != 1):
                raise ValueError('invalid private error journal')
            entry = dict(stage=stage, case=public_id, error_type=type(exc).__name__, detail=str(exc))
            os.write(fd, (json.dumps(entry, ensure_ascii=True) + '\n').encode())
            os.fsync(fd)
        finally:
            os.close(fd)

    expected_host, expected_scorer = args.host_sha256, args.scorer_sha256
    def guard():
        if digest_file(HOST) != expected_host or digest_file(SCORER) != expected_scorer:
            raise RuntimeError('host or scorer source changed')
    guard()
    if args.key_file == args.checkpoint:
        raise ValueError('continuation key and checkpoint must differ')
    approval = load_approval(args.approval, args.approval_sha256) if args.approval else None
    cache = {'loaded': False, 'error': False}
    def setup():
        if not cache['loaded']:
            cache['loaded'] = True
            try:
                guard()
                cache['inputs'], cache['selector'], cache['parent'] = prepare_inputs()
                case_ids = cache['selector'].case_ids()
                if len(case_ids) != 12 or len(set(case_ids)) != 12:
                    raise ValueError('source case count differs')
                if approval:
                    if {v['case_id'] for v in approval.values()} != set(case_ids):
                        raise ValueError('approved cases differ')
                    cache['mapping'] = {k: v['case_id'] for k, v in approval.items()}
                else:
                    cache['mapping'] = dict(zip(PUBLIC_IDS, case_ids))
                guard()
            except Exception as exc:
                record_error('setup', None, exc)
                cache['error'] = True
        if cache['error']:
            raise BlockedCase('source setup failed')
    def fresh(public_id):
        setup(); guard()
        return RestrictedSourceIncidentV1(cache['inputs'], cache['selector'], cache['parent'],
            case_id=cache['mapping'][public_id], containment_config=CONFIG, pressure_scale=1, opt_in=True)
    def factory(public_id):
        try:
            host = fresh(public_id)
            if approval is None:
                return UnscoredHost(host)
            entry = approval[public_id]
            return RestrictedSourceScoredV1(host, scoring_mask=entry['mask'], expected_identity=entry['identity'],
                                            public_population=entry['public_population'], opt_in=True)
        except BlockedCase:
            raise
        except Exception as exc:
            record_error('factory', public_id, exc)
            raise
    def policy_for(case):
        return PassivePolicy(guard, lambda exc: record_error('policy', case, exc))
    class Continuation:
        def __init__(self, key):
            self._key = key
        def capture(self, host, policy):
            guard()
            if policy is not None and type(policy) is not PassivePolicy:
                raise ValueError('unsupported policy state')
            wrapped = host._host if type(host) is UnscoredHost else host
            value = {'version': VERSION, 'policy': 'none' if policy is None else 'passive-one-minute-v1',
                     'host': wrapped.checkpoint()}
            return json.dumps(value, allow_nan=False, separators=(',', ':')).encode()
        def seal(self, body):
            return hmac.digest(self._key, body, 'sha256') + body
        def open(self, sealed):
            if len(sealed) < 32 or not hmac.compare_digest(sealed[:32], hmac.digest(self._key, sealed[32:], 'sha256')):
                raise ValueError('continuation authentication failed')
            return sealed[32:]
        def restore(self, public_id, state):
            import adapter_v1 as api
            value = json.loads(state)
            if (type(value) is not dict or set(value) != {'version', 'policy', 'host'}
                    or value['version'] != VERSION or value['policy'] not in ('none', 'passive-one-minute-v1')):
                raise ValueError('policy continuation differs')
            host = factory(public_id)
            wrapped = host._host if type(host) is UnscoredHost else host
            wrapped.restore(value['host'], expected_checkpoint_sha256=api._hash(value['host']))
            guard()
            return host, None if value['policy'] == 'none' else policy_for(public_id)
    def verify(public_id, host):
        guard()
        if approval is None:
            return dict(status='unapproved', scope=SCOPE, reward_version=REWARD_VERSION,
                        verified=False, score_eligible=False, score=None)
        entry = approval[public_id]
        result = verify_outcome(host, fresh_host=lambda: fresh(public_id),
                                expected_identity=entry['identity'], scoring_mask=entry['mask'])
        guard()
        return result
    mode = 'approved' if approval else 'unscored'
    run_id = hashlib.sha256(json.dumps([VERSION, digest_file(Path(__file__)), expected_host, expected_scorer,
                                       args.approval_sha256 if approval else mode], separators=(',', ':')).encode()).hexdigest()
    if not args.resume and os.path.lexists(args.checkpoint):
        raise FileExistsError('checkpoint already exists')
    key = load_key(args.key_file, resume=args.resume)
    return qualify(PUBLIC_IDS, checkpoint=args.checkpoint, run_id=run_id, make_environment=factory,
                   make_policy=policy_for, verify_outcome=verify, state_adapter=Continuation(key),
                   wall_seconds=args.wall_seconds, max_decisions=args.max_decisions, resume=args.resume)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint', type=Path, required=True)
    parser.add_argument('--key-file', type=Path, required=True)
    parser.add_argument('--host-sha256', required=True)
    parser.add_argument('--scorer-sha256', required=True)
    parser.add_argument('--approval', type=Path)
    parser.add_argument('--approval-sha256')
    parser.add_argument('--wall-seconds', type=float, default=300)
    parser.add_argument('--max-decisions', type=int, default=1)
    parser.add_argument('--resume', action='store_true')
    args = parser.parse_args()
    if (not math.isfinite(args.wall_seconds) or not 0 < args.wall_seconds <= 1800
            or not 1 <= args.max_decisions <= 1440):
        parser.error('invalid bounded run limits')
    if bool(args.approval) != bool(args.approval_sha256):
        parser.error('approval and its independent SHA-256 are required together')
    for pin in (args.host_sha256, args.scorer_sha256, *([args.approval_sha256] if args.approval else [])):
        if len(pin) != 64 or any(c not in '0123456789abcdef' for c in pin):
            parser.error('invalid SHA-256')
    if hasattr(os, 'sched_getaffinity') and hasattr(os, 'sched_setaffinity'):
        allowed = os.sched_getaffinity(0)
        os.sched_setaffinity(0, {min(allowed)})
    started = time.monotonic()
    try:
        result = run(args)
    except Exception:
        print('Private run failed; existing checkpoint was retained.', file=sys.stderr)
        return 1
    counts = {key: sum(row['status'] == key for row in result['cases'])
              for key in ('restricted_scored', 'censored', 'blocked', 'incomplete')}
    print(json.dumps(dict(version=VERSION, mode='approved' if args.approval else 'unscored',
                          scope='restricted_no_ground_no_evac', counts=counts,
                          elapsed_seconds=round(time.monotonic()-started, 2))))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
