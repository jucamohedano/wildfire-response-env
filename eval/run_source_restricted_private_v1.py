def digest_file(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def pinned_doc(path, pin):
    import adapter_v1 as api
    if path.is_symlink():
        raise ValueError('source document symlink')
    value = json.loads(path.read_bytes())
    if value.get('sha256') != pin or api._hash({k: v for k, v in value.items() if k != 'sha256'}) != pin:
        raise ValueError('source document mismatch')
    return value


def load_approval(path, pin):
    path = Path(path)
    info = path.lstat()
    if (not stat.S_ISREG(info.st_mode) or info.st_uid != os.geteuid()
            or info.st_mode & 0o077 or info.st_nlink != 1):
        raise ValueError('approval must be a private regular file')
    if digest_file(path) != pin:
        raise ValueError('approval pin differs')
    value = json.loads(path.read_bytes())
    if (type(value) is not dict or set(value) != {'version', 'cases'}
            or value['version'] != 'wildfire-restricted-evaluation-approval-v1'
            or type(value['cases']) is not dict or set(value['cases']) != set(PUBLIC_IDS)):
        raise ValueError('invalid approval')
    for item in value['cases'].values():
        if (type(item) is not dict or set(item) != {'case_id', 'mask', 'public_population', 'identity'}
                or type(item['case_id']) is not str or type(item['mask']) is not list
                or type(item['public_population']) is not list or type(item['identity']) is not dict):
            raise ValueError('invalid approval case')
    if len({item['case_id'] for item in value['cases'].values()}) != 12:
        raise ValueError('approval case mapping differs')
    return value['cases']


